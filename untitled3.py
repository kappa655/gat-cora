import networkx as nx
import matplotlib.pyplot as plt

# 1. Εκτέλεση του μοντέλου σου με return_att=True
model.eval()
with torch.no_grad():
    out, att_edge_index, alpha = model(data.x, data.edge_index, return_att=True)

# Παίρνουμε το μέσο όρο των 4 heads που όρισες (NUM_HEADS = 4)
alpha_mean = alpha.mean(dim=1).squeeze()

# 2. Επιλογή Κεντρικού Κόμβου
target_node = 0  # Μπορείς να βάλεις όποιον κόμβο θέλεις (0 - 2707)

# Βρίσκουμε τις ακμές που συνδέονται ΜΟΝΟ με τον target_node
mask = (att_edge_index[0] == target_node) | (att_edge_index[1] == target_node)
sub_edges = att_edge_index[:, mask]
sub_weights = alpha_mean[mask]

# 3. Δημιουργία Graph & Υπολογισμός Ποσοστών (%)
G = nx.DiGraph()
total_weight = sub_weights.sum().item() if sub_weights.sum().item() > 0 else 1.0

edge_labels = {}
for i in range(sub_edges.shape[1]):
    src = sub_edges[0, i].item()
    dst = sub_edges[1, i].item()
    w = sub_weights[i].item()

    # Υπολογισμός ποσοστού % επί του συνόλου της προσοχής του κόμβου
    percentage = (w / total_weight) * 100

    G.add_edge(src, dst, weight=w)
    edge_labels[(src, dst)] = f"{percentage:.1f}%"

# 4. Σχεδίαση του Γράφου
plt.figure(figsize=(10, 8), dpi=150)
pos = nx.spring_layout(G, seed=42)  # Σταθερή διάταξη

# Πάχος γραμμών ανάλογα με το weight
weights = [G[u][v]['weight'] for u, v in G.edges()]
max_w = max(weights) if max(weights) > 0 else 1
edge_widths = [(w / max_w) * 5 + 1.0 for w in weights]

# Χρώματα: Κόκκινο ο κεντρικός κόμβος, Μπλε οι γείτονες
node_colors = ['#E63946' if node == target_node else '#457B9D' for node in G.nodes()]

# Κόμβοι & Labels Κόμβων
nx.draw_networkx_nodes(G, pos, node_size=800, node_color=node_colors)
nx.draw_networkx_labels(G, pos, font_color='white', font_weight='bold', font_size=10)

# Ακμές
