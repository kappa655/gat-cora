import torch
import torch.nn.functional as F
from torch_geometric.nn import GATConv

HIDDEN_FEATURES = 32
NUM_HEADS = 4

class cora(torch.nn.Module):
    def __init__(self, num_features, hidden_features, out_features, num_head):
        super().__init__()
        self.conv1 = GATConv(in_channels=num_features, out_channels=hidden_features, heads=num_head, dropout=0.6)
        self.conv2 = GATConv(in_channels=hidden_features * num_head, out_channels=out_features, dropout=0.4, concat=False)

    def forward(self, input_feature, edge_index, return_att=False):
        x = F.dropout(input=input_feature, p=0.6, training=self.training)

        # Αν ζητήσουμε τα weights, παίρνουμε τα attention weights από το 1ο layer (conv1)
        if return_att:
            x, (att_edge_index, alpha) = self.conv1(x, edge_index, return_attention_weights=True)
        else:
            x = self.conv1(x, edge_index)

        x = F.elu(x)
        x = F.dropout(input=x, p=0.6, training=self.training)
        x = self.conv2(x, edge_index)

        if return_att:
            return x, att_edge_index, alpha
        return x

device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
model = cora(data.num_features, HIDDEN_FEATURES, dataset.num_classes, NUM_HEADS).to(device)
data = data.to(device)

criterion = torch.nn.CrossEntropyLoss()
optimizer = torch.optim.Adam(model.parameters(), lr = 0.01, weight_decay=5e-4)

def train():
    model.train()
    optimizer.zero_grad()
    out = model.forward(data.x, data.edge_index)
    loss = criterion(out[data.train_mask], data.y[data.train_mask])
    loss.backward()
    optimizer.step()
    return loss.item()



@torch.no_grad()
def test():
  model.eval()
  out = model.forward(data.x, data.edge_index)
  pred = out.argmax(dim=1)

  accuracy = []
  for mask in [data.train_mask, data.val_mask, data.test_mask]:
    correct = (pred[mask] == data.y[mask]).sum()
    ratio = (int(correct) / int(mask.sum()))
    accuracy.append(ratio)
  return accuracy



# Run training across 200 epochs
for epoch in range(1, 201):
    loss = train()
    if epoch % 20 == 0:
        train_acc, val_acc, test_acc = test()
        print(f"Epoch {epoch:03d} | Loss: {loss:.4f} | Train Acc: {train_acc*100:.1f}% | Val Acc: {val_acc*100:.1f}% | Test Acc: {test_acc*100:.1f}%")

